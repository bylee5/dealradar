OTHER = "기타"


def _norm(text):
    return (text or "").lower()


def _match(text, categories):
    for name, kws in categories:
        for kw in kws:
            k = _norm(kw)
            if k and k in text:
                return name
    return None


def classify(title, categories, source_category=None):
    """제목으로 먼저 분류하고, 안 되면 원본 사이트의 카테고리명으로 분류한다.

    categories: [(name, [kw, ...]), ...]
    """
    return (_match(_norm(title), categories)
            or (_match(_norm(source_category), categories) if source_category else None)
            or OTHER)
